// The repositories the agent starts in: the same three Dart packages at three
// stages of Melos adoption. `acme_cli` depends on `acme_core`, `acme_utils`
// stands alone, and only `acme_core` and `acme_utils` have tests.

type Files = Record<string, string>

/** How a package's pubspec.yaml links it to the others at each stage. */
type Stage = 'standalone' | 'melos-6' | 'melos-8'

const sdk: Record<Stage, string> = {
  standalone: '^3.9.0',
  'melos-6': '">=3.0.0 <4.0.0"',
  'melos-8': '^3.9.0',
}

function pubspec(stage: Stage, name: string, extra: string) {
  return (
    `name: ${name}\n` +
    'version: 1.0.0\n' +
    'publish_to: none\n\n' +
    `environment:\n  sdk: ${sdk[stage]}\n` +
    (stage === 'melos-8' ? 'resolution: workspace\n' : '') +
    extra
  )
}

const testDependency = '\ndev_dependencies:\n  test: ^1.25.0\n'

function packages(stage: Stage): Files {
  const core = stage === 'standalone' ? '\n    path: ../acme_core' : ' ^1.0.0'
  return {
    'packages/acme_core/pubspec.yaml': pubspec(stage, 'acme_core', testDependency),
    'packages/acme_core/lib/acme_core.dart':
      "/// Greets [name].\nString greet(String name) => 'Hello, $name!';\n",
    'packages/acme_core/test/acme_core_test.dart':
      "import 'package:acme_core/acme_core.dart';\n" +
      "import 'package:test/test.dart';\n\n" +
      'void main() {\n' +
      "  test('greets by name', () => expect(greet('Ada'), 'Hello, Ada!'));\n" +
      '}\n',

    'packages/acme_cli/pubspec.yaml': pubspec(
      stage,
      'acme_cli',
      `\ndependencies:\n  acme_core:${core}\n`,
    ),
    'packages/acme_cli/bin/acme.dart':
      "import 'package:acme_core/acme_core.dart';\n\n" +
      'void main(List<String> args) {\n' +
      "  print(greet(args.isEmpty ? 'world' : args.first));\n" +
      '}\n',

    'packages/acme_utils/pubspec.yaml': pubspec(stage, 'acme_utils', testDependency),
    'packages/acme_utils/lib/acme_utils.dart':
      '/// Upper cases [text].\nString shout(String text) => text.toUpperCase();\n',
    'packages/acme_utils/test/acme_utils_test.dart':
      "import 'package:acme_utils/acme_utils.dart';\n" +
      "import 'package:test/test.dart';\n\n" +
      'void main() {\n' +
      "  test('shouts', () => expect(shout('hi'), 'HI'));\n" +
      '}\n',
  }
}

