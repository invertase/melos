/**
 * Writes `lib/src/assets.g.dart` from the files in `assets/`, and says which
 * package it ran in, so the checks can tell which packages a script reached.
 */
const embedAssets =
  "import 'dart:convert';\n" +
  "import 'dart:io';\n\n" +
  'void main() {\n' +
  '  final package = Directory.current.uri.pathSegments.lastWhere(\n' +
  '    (segment) => segment.isNotEmpty,\n' +
  '  );\n' +
  "  final assets = Directory('assets').listSync().whereType<File>().toList()\n" +
  '    ..sort((a, b) => a.path.compareTo(b.path));\n' +
  '  final out = StringBuffer()\n' +
  "    ..writeln('// Generated by tool/embed_assets.dart. Do not edit.')\n" +
  "    ..writeln('const assets = <String, String>{');\n" +
  '  for (final asset in assets) {\n' +
  '    final name = jsonEncode(asset.uri.pathSegments.last);\n' +
  "    out.writeln('  $name: ${jsonEncode(asset.readAsStringSync())},');\n" +
  '  }\n' +
  "  out.writeln('};');\n" +
  "  File('lib/src/assets.g.dart')\n" +
  '    ..createSync(recursive: true)\n' +
  '    ..writeAsStringSync(out.toString());\n' +
  "  print('embed_assets: wrote ${assets.length} assets for $package');\n" +
  '}\n'

